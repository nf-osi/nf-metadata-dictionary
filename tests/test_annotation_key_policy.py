def test_default_view_columns_are_not_reported_as_unknown_keys(canon, index):
    # A view scope returns Synapse's own default columns alongside real
    # annotations. Reporting `modifiedOn` as an unrecognised annotation key
    # makes the unknown bucket noise, and noise gets ignored.
    summary = policy.classify_key_inventory(
        {'modifiedOn', 'projectId', 'versionNumber', 'dataFileName', 'tissue'},
        canon=canon, index=index,
    )
    assert 'modifiedOn' not in summary.unknown
    assert 'projectId' not in summary.unknown
    assert 'versionNumber' not in summary.unknown
    assert 'dataFileName' not in summary.unknown
    # A genuine custom annotation still lands in unknown.
    assert 'tissue' in summary.unknown


def test_near_miss_typo_is_separated_from_genuine_custom_annotations(canon, index):
    # Real key observed in syn51356705: `progrssReportNumber`, one character off
    # `progressReportNumber`. That is a data bug worth surfacing, whereas
    # `tissue` is a legitimate annotation outside the schema.
    summary = policy.classify_key_inventory(
        {'progrssReportNumber', 'tissue', 'sampleSite'}, canon=canon, index=index,
    )
    assert summary.near_misses == {'progrssReportNumber': 'progressReportNumber'}
    assert set(summary.unknown) == {'tissue', 'sampleSite'}


def test_near_miss_detection_can_be_disabled(canon, index):
    summary = policy.classify_key_inventory(
        {'progrssReportNumber'}, canon=canon, index=index, detect_typos=False,
    )
    assert summary.near_misses == {}
    assert summary.unknown == ['progrssReportNumber']


def test_near_misses_are_never_queued_for_a_write(canon, index):
    # A typo is not a case variant, so decide() must not try to repair it.
    decision = policy.decide('progrssReportNumber', {'progrssReportNumber': [3]},
                             canon=canon, index=index)
    assert decision.action == policy.Action.SKIP
    assert decision.reason == 'unknown_key'
