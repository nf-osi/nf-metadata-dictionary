#!/usr/bin/env python3
"""
Tests for the annotation key policy used to clean up mis-cased annotation keys
on NF-OSI Synapse entities (issue #939).

Every test here is offline. The policy module deliberately does not import
synapseclient, so the decision rules that govern destructive writes can be
exercised in CI without credentials or network access.

Two independent classifiers are under test:

* Rule A - a legacy schematic path keyed annotations off the schema's PascalCase
  ``rdfs:label`` instead of the camelCase ``sms:displayName``, leaving pairs like
  ``Age``/``age`` on the same entity.
* Rule B - case-insensitive collision, which catches former slot names left
  behind by schema renames (``timePointUnit`` -> ``timepointUnit``). Rule A
  cannot see these at all.
"""

