def test_stray_index_never_maps_a_name_to_itself(index):
    for stray, canonical in index.stray_index.items():
        assert stray != canonical, f'{stray} would be renamed to itself'


def test_stray_index_excludes_self_pascal_canonical_slots(index, canon):
    # These 9 canonical slots already start uppercase, so to_stray() is the
    # identity. Without the guard the tool flags valid `Component` data as a
    # stray and tries to rename it to itself.
    self_pascal = {c for c in canon if policy.to_stray(c) == c}
    assert self_pascal == {
        'Component', 'Filename', 'GIST', 'InChIKey', 'IrisLischNodules',
        'MPNSTCharacterization', 'MRISequence', 'Resource_id', 'WHOPerformanceStatus',
    }
    for name in self_pascal:
        assert name not in index.stray_index


def test_stray_index_values_are_all_canonical(index, canon):
    for canonical in index.stray_index.values():
        assert canonical in canon


def test_no_two_canonical_names_collide_onto_one_stray(canon):
    # True today. If a schema change breaks it, a stray key becomes ambiguous
    # and must not be auto-renamed, so this needs to fail loudly.
    seen = {}
    for name in canon:
        stray = policy.to_stray(name)
        if stray == name:
            continue
        assert stray not in seen, f'{stray} maps to both {seen.get(stray)} and {name}'
        seen[stray] = name


def test_legacy_aliases_resolve_to_current_canonical_names(index, canon):
    # Five verified exceptions the PascalCase rule cannot derive. They have zero
    # hits in the wild today; they are kept so coverage claims stay honest.
    assert policy.LEGACY_ALIASES == {
        'Breast Cancer': 'breastCancer',
        'Vestibular Schwannoma': 'vestibularSchwannoma',
        'CroissantFileS3Object': 'croissant_file_s3_object',
        'ResourceId': 'Resource_id',
        'eTag': 'etag',
    }
    for target in policy.LEGACY_ALIASES.values():
        assert target in canon


