@pytest.mark.parametrize('variant,canonical', [
    ('timePointUnit', 'timepointUnit'),
    ('specimenIdSource', 'specimenIDSource'),
    ('experimentalTimePoint', 'experimentalTimepoint'),
    ('studyID', 'studyId'),
    ('dataSubType', 'dataSubtype'),
    ('individualId', 'individualID'),
    ('parentSpecimenId', 'parentSpecimenID'),
    ('component', 'Component'),
    ('filename', 'Filename'),
])
def test_case_variant_drift_resolves_to_the_canonical_slot(variant, canonical, canon, index):
    # None of these are derivable from the PascalCase rule; they are former slot
    # names left behind by schema renames and are only caught by rule B.
    resolved, rule = policy.resolve_canonical(variant, canon=canon, index=index)
    assert resolved == canonical
    assert rule == 'case_variant'


def test_orphan_case_variant_is_renamed(canon, index):
    decision = policy.decide('timePointUnit', {'timePointUnit': ['days']}, canon=canon, index=index)
    assert decision.action == policy.Action.RENAME_STRAY
    assert decision.canonical_key == 'timepointUnit'


def test_pascal_rule_alone_would_miss_etag(canon, index):
    # to_stray('etag') is 'Etag', not 'eTag', so only the alias table catches it.
    assert policy.to_stray('etag') == 'Etag'
    resolved, _ = policy.resolve_canonical('eTag', canon=canon, index=index)
    assert resolved == 'etag'


