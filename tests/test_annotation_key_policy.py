# ---------------------------------------------------------------------------
# Value comparison
# ---------------------------------------------------------------------------

def test_scalar_and_single_item_list_are_equivalent():
    assert policy.values_equivalent([1.5], 1.5)
    assert policy.values_equivalent('brain', ['brain'])


def test_int_and_string_forms_differ_strictly_but_match_loosely():
    # The real syn64420376 case: IndividualID is INTEGER 1119 while
    # individualID is STRING "1119". Equal in intent, unequal in type.
    assert not policy.values_equivalent([1119], ['1119'])
    assert policy.values_equivalent([1119], ['1119'], loose=True)
    assert policy.values_equivalent([1.0], ['1'], loose=True)


def test_numerically_identical_values_are_strictly_equivalent():
    assert policy.values_equivalent([1], [1.0])


def test_list_order_matters_strictly_but_not_loosely():
    # Conservative on purpose: a reordered list is reported for review rather
    # than silently treated as a duplicate and deleted.
    assert not policy.values_equivalent(['a', 'b'], ['b', 'a'])
    assert policy.values_equivalent(['a', 'b'], ['b', 'a'], loose=True)


def test_booleans_match_their_string_form_only_loosely():
    assert not policy.values_equivalent([True], ['true'])
    assert policy.values_equivalent([True], ['true'], loose=True)


def test_whitespace_is_stripped_before_comparison():
    assert policy.values_equivalent(['  brain '], ['brain'])


def test_truncated_values_are_never_equivalent():
    # Executable documentation of why an EntityView is unsafe as a comparison
    # source: view STRING columns are declared at maximum_size=80, so a longer
    # value comes back truncated. Deciding "equal, drop one" from a truncated
    # read could destroy the only surviving copy.
    long_value = 'x' * 200
    assert not policy.values_equivalent([long_value], [long_value[:80]])
    assert not policy.values_equivalent([long_value], [long_value[:80]], loose=True)


@pytest.mark.parametrize('empty', [None, [], [''], ['   '], [None], ''])
def test_empty_value_detection(empty):
    assert policy.is_empty_value(empty)


@pytest.mark.parametrize('present', [[0], [False], ['x'], 0, False])
def test_zero_and_false_are_not_empty(present):
    # Dropping a legitimate 0 or False as if it were absent would lose data.
    assert not policy.is_empty_value(present)


