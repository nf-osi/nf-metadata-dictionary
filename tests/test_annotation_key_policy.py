def test_duplicate_with_identical_value_is_dropped(canon, index):
    annotations = {'Age': [1.5], 'age': [1.5]}
    decision = policy.decide('Age', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.DROP_STRAY
    assert decision.canonical_key == 'age'
    assert decision.reason == 'values_equivalent'


def test_duplicate_differing_only_in_type_is_reported_not_dropped(canon, index):
    annotations = {'IndividualID': [1119], 'individualID': ['1119']}
    decision = policy.decide('IndividualID', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.REPORT_CONFLICT
    assert decision.reason == 'type_coercion'


def test_loose_compare_promotes_type_coercion_to_a_drop(canon, index):
    annotations = {'IndividualID': [1119], 'individualID': ['1119']}
    decision = policy.decide('IndividualID', annotations, canon=canon, index=index, loose_compare=True)
    assert decision.action == policy.Action.DROP_STRAY


def test_duplicate_with_genuinely_different_values_is_never_touched(canon, index):
    annotations = {'Organ': ['nerves'], 'organ': ['brain']}
    decision = policy.decide('Organ', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.REPORT_CONFLICT
    assert decision.reason == 'values_differ'


def test_empty_canonical_alongside_populated_stray_is_reported(canon, index):
    annotations = {'Sex': ['Female'], 'sex': []}
    decision = policy.decide('Sex', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.REPORT_CONFLICT
    assert decision.reason == 'canonical_empty'


def test_empty_stray_is_dropped_even_when_the_canonical_value_differs(canon, index):
    # Ordering matters: the empty check has to run before value comparison, or an
    # empty stray next to a populated canonical is misfiled as a conflict and
    # the noise is never cleaned up.
    annotations = {'Organ': [''], 'organ': ['nerves']}
    decision = policy.decide('Organ', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.DROP_STRAY
    assert decision.reason == 'empty_stray_value'


def test_empty_stray_targeting_a_reserved_field_is_still_droppable(canon, index):
    # Removing a stray `Description` key does not write to the reserved
    # `description` entity property, so dropping empty noise is safe.
    decision = policy.decide('Description', {'Description': ['']}, canon=canon, index=index)
    assert decision.action == policy.Action.DROP_STRAY


def test_duplicate_reserved_name_with_equal_values_is_dropped(canon, index):
    # Real case in syn51356705: both `ContentType` and `contentType` are present.
    # Dropping the stray is safe because nothing is written to the reserved name.
    annotations = {'ContentType': ['dataset'], 'contentType': ['dataset']}
    decision = policy.decide('ContentType', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.DROP_STRAY


def test_orphan_stray_is_renamed_to_the_canonical_name(canon, index):
    annotations = {'Nf2Genotype': ['-/-']}
    decision = policy.decide('Nf2Genotype', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.RENAME_STRAY
    assert decision.canonical_key == 'nf2Genotype'


def test_orphan_with_a_third_case_variant_present_is_reported(canon, index):
    # Real case in syn8012530, which carries both `TimePointUnit` and
    # `timePointUnit`. Renaming either would silently clobber the other.
    annotations = {'TimePointUnit': ['days'], 'timePointUnit': ['weeks']}
    decision = policy.decide('TimePointUnit', annotations, canon=canon, index=index)
    assert decision.action == policy.Action.REPORT_CONFLICT
    assert decision.reason == 'multi_variant'


def test_alias_pointing_at_a_retired_slot_is_reported_not_renamed(canon, index):
    # Renaming into a slot the schema no longer defines would resurrect a dead
    # field into the portal namespace.
    shrunk = frozenset(canon - {'nf2Genotype'})
    shrunk_index = policy.KeyIndex.build(canon)  # index still knows the old mapping
    decision = policy.decide('Nf2Genotype', {'Nf2Genotype': ['-/-']}, canon=shrunk, index=shrunk_index)
    assert decision.action == policy.Action.REPORT_RETIRED


