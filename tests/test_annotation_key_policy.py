def test_decide_entity_covers_the_real_syn64420376_annotations(canon, index):
    annotations = json.loads((FIXTURE_DIR / 'syn64420376_annotations.json').read_text())
    decisions = {d.stray_key: d for d in policy.decide_entity(annotations, canon=canon, index=index)}

    for stray, canonical in [('Age', 'age'), ('Sex', 'sex'), ('Assay', 'assay'),
                             ('Organ', 'organ'), ('AgeUnit', 'ageUnit'), ('Species', 'species'),
                             ('Comments', 'comments'), ('DataType', 'dataType'),
                             ('Platform', 'platform'), ('Diagnosis', 'diagnosis'),
                             ('TumorType', 'tumorType'), ('FileFormat', 'fileFormat'),
                             ('DataSubtype', 'dataSubtype'), ('ResourceType', 'resourceType'),
                             ('ModelSystemName', 'modelSystemName')]:
        assert decisions[stray].action == policy.Action.DROP_STRAY, stray
        assert decisions[stray].canonical_key == canonical

    # INTEGER 1119 vs STRING "1119" - reported, not silently dropped.
    assert decisions['IndividualID'].action == policy.Action.REPORT_CONFLICT
    assert decisions['IndividualID'].reason == 'type_coercion'

    # Schematic infrastructure and canonical keys are left alone.
    assert decisions['Id'].action == policy.Action.SKIP
    assert decisions['EntityId'].action == policy.Action.SKIP
    assert decisions['Component'].action == policy.Action.SKIP


def test_apply_decisions_drops_only_the_named_key(canon, index):
    annotations = {'Age': [1.5], 'age': [1.5], 'sex': ['Female']}
    decisions = [policy.decide('Age', annotations, canon=canon, index=index)]
    result = policy.apply_decisions(annotations, decisions)
    assert result == {'age': [1.5], 'sex': ['Female']}


def test_apply_decisions_renames_by_moving_the_value(canon, index):
    annotations = {'Nf2Genotype': ['-/-'], 'age': [1.5]}
    decisions = [policy.decide('Nf2Genotype', annotations, canon=canon, index=index)]
    result = policy.apply_decisions(annotations, decisions)
    assert result == {'nf2Genotype': ['-/-'], 'age': [1.5]}


def test_apply_decisions_does_not_mutate_its_input(canon, index):
    annotations = {'Age': [1.5], 'age': [1.5]}
    before = dict(annotations)
    policy.apply_decisions(annotations, [policy.decide('Age', annotations, canon=canon, index=index)])
    assert annotations == before


def test_apply_decisions_ignores_report_only_actions(canon, index):
    annotations = {'Organ': ['nerves'], 'organ': ['brain']}
    decisions = [policy.decide('Organ', annotations, canon=canon, index=index)]
    assert policy.apply_decisions(annotations, decisions) == annotations


def test_apply_decisions_is_idempotent(canon, index):
    annotations = {'Age': [1.5], 'age': [1.5]}
    decisions = [policy.decide('Age', annotations, canon=canon, index=index)]
    once = policy.apply_decisions(annotations, decisions)
    twice = policy.apply_decisions(once, policy.decide_entity(once, canon=canon, index=index))
    assert once == twice


def test_apply_decisions_raises_on_a_key_that_is_no_longer_present():
    # Silently no-oping here would let a stale plan report success without
    # having changed anything.
    stale = policy.Decision(
        action=policy.Action.DROP_STRAY, stray_key='Age', canonical_key='age', reason='values_equivalent',
    )
    with pytest.raises(KeyError):
        policy.apply_decisions({'age': [1.5]}, [stale])


def test_rename_refuses_to_overwrite_an_existing_canonical_key():
    # Defence in depth: decide() already routes this to a conflict, but
    # apply_decisions must not clobber even if handed a bad plan.
    bad = policy.Decision(
        action=policy.Action.RENAME_STRAY, stray_key='Age', canonical_key='age', reason='orphan',
    )
    with pytest.raises(ValueError):
        policy.apply_decisions({'Age': [1.5], 'age': [2.0]}, [bad])


